import { relations } from "drizzle-orm";
import {
  pgTable,
  text,
  bigint,
  timestamp,
  boolean,
  integer,
  index,
  uniqueIndex,
  serial,
  customType,
} from "drizzle-orm/pg-core";

const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType() {
    return "bytea";
  },
});

export const applications = pgTable("applications", {
  id: serial("id").primaryKey().notNull(),
  role: text("role").notNull(),
  company_name: text("company_name").notNull(),
  location: text("location").notNull(),
  status: text("status").notNull(),
  date_applied: timestamp("date_applied", { mode: "date" }),
  /** When the user plans to apply. Mostly useful while the status is "Not Applied". */
  planned_date: timestamp("planned_date", { mode: "date" }),
  /** When to check back in on the application. */
  follow_up_date: timestamp("follow_up_date", { mode: "date" }),
  notes: text("notes"),
  link: text("link"),
  salary: text("salary"),
  rate: text("rate"),
  user_id: text("user_id").notNull(),
  created_at: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updated_at: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
});

/** One PDF per application. Bytes live in Postgres; deleting the application drops the file. */
export const resumes = pgTable("resumes", {
  id: serial("id").primaryKey().notNull(),
  application_id: integer("application_id")
    .notNull()
    .unique()
    .references(() => applications.id, { onDelete: "cascade" }),
  user_id: text("user_id").notNull(),
  file_name: text("file_name").notNull(),
  content_type: text("content_type").notNull(),
  size: integer("size").notNull(),
  data: bytea("data").notNull(),
  created_at: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updated_at: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
});

